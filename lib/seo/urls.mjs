/** Builds absolute URLs on the canonical origin and finds pages in data/discovery.json. */

export const GENERATED_NOTE = "Generated by scripts/generate-seo.mjs from data/discovery.json. Do not edit."

/**
 * @param {import("./schema.mjs").Discovery} discovery
 * @param {string} path
 * @returns {string}
 */
export function absoluteUrl(discovery, path) {
  return new URL(path, discovery.url).toString()
}

function hasPath(path, page) {
  return page.path === path
}

/**
 * @param {import("./schema.mjs").Discovery} discovery
 * @param {string} path
 * @returns {import("./schema.mjs").Page}
 */
export function findPage(discovery, path) {
  const page = discovery.pages.find(hasPath.bind(null, path))
  if (!page) throw new Error(`data/discovery.json has no page ${path}`)
  return page
}

/** The public file path of a site path, for example /og.png becomes public/og.png. */
export function publicFile(path) {
  return `public${path}`
}
